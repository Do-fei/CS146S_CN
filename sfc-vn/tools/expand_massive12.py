#!/usr/bin/env python3
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1] / "docs" / "novel"

APPENDS = {
"00-序.md": """
你读这部小说，像走小的路。宽的大路是结案、请假、忘记。窄的小的路是发送失败、停止键、漏句爬回。赵宜叫同桌。你应的不是名字，是位置。位置在，故事就在。""",

"17-小的路.md": """
第十七周，你们仍走小的路。不是因为它神秘。是因为它写不进报告。写不进，就不容易被大路收走。她抓袖口。你应：在。不是告白。是确认。确认布料还在。确认漏句还在。确认第三排靠窗还坐着两个人。两个解。各走各的。草稿纸还能碰面。够了。""",

"18-漏句.md": """
正本最后一页，你和她并排看数学书。便利贴压着便利贴。方程两个解。我们选了漏的那一个。她忽然说：同桌，我数学还是不会。你说：我知道。她说：你知道就行。你知道，就够把我拼回来。你嗯。不补太多。补太多，像还要被听完。窗外22:59。秒针抖。你不管。你管袖口还在。够了。正本到此。""",

"01-发送失败.md": """
发送失败之后，你把她的头像放大。齐刘海，笑成一条线。线下面，红色感叹号。你缩小。又放大。像确认照片里的人还会不会出现。不会出现。出现，在第三排靠窗的空位里，在桌角结皮的豆浆里，在发送失败后面的所有章里。你关屏。去上学。空位在。你也在。也在，就够你等到十一点。""",

"09-西单.md": """
到西单之前，你在桥上选了阿青。选阿青，是选声音，选停止键，选漏句。选完，不能回头。回头，像还想去听完整盘。你不。你要她爬回来。爬回来，不完整，能抓袖口。西单卷帘门缝窄。你侧身穿。像侧身进「我选——」后面那个空。空里，键在等你。你还不按。按了，是第十五章。现在，你只进门。进门，暖黄，旧塑料，橘子皮。赵宜（未完成）。停。""",
}

def main():
    for fn, text in APPENDS.items():
        path = ROOT / fn
        content = path.read_text(encoding="utf-8")
        tag = f"<!--EXPAND12:{fn}-->"
        if tag in content:
            print(f"skip {fn}")
            continue
        path.write_text(content.rstrip() + "\n\n" + tag + "\n" + text.strip() + "\n", encoding="utf-8")
        print(f"append {fn} (+{len(text)})")

if __name__ == "__main__":
    main()
