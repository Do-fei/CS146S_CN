def bank_for(chapter_file: str) -> list[str]:
    ch_num = chapter_file.split("-")[0]
    seed = sum(ord(c) for c in chapter_file) + 4880
    bank: list[str] = list(CORES.get(ch_num, []))
    bank.extend(gen_long_scenes(ch_num, 220, seed))
    return bank
