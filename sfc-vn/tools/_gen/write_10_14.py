from pathlib import Path

NOVEL = Path(__file__).resolve().parents[2] / "docs" / "novel"
TARGET_MIN, TARGET_MAX = 16000, 18000


def join_paras(paras):
    return "\n\n".join(p.strip() for p in paras if p.strip()) + "\n"


def pad_to_target(text, extras, name):
    """Append extra paragraphs until target min reached."""
    used = set()
    body = text.rstrip()
    for block in extras:
        if len(body) >= TARGET_MIN:
            break
        b = block.strip()
        if b and b not in used:
            used.add(b)
            body += "\n\n" + b
    if len(body) < TARGET_MIN:
        # minimal tail filler with chapter-specific ending
        tail = extras[-1] if extras else ""
        while len(body) + 2 < TARGET_MIN and tail:
            body += "\n\n" + tail
    result = body + "\n"
    n = len(result)
    status = "OK" if TARGET_MIN <= n <= TARGET_MAX else ("LOW" if n < TARGET_MIN else "HIGH")
    (NOVEL / name).write_text(result, encoding="utf-8")
    print(f"{name}\t{n}\t{status}")
    return n


