def load_scene_files(tools_dir) -> list[str]:
    scenes: list[str] = []
    scene_dir = tools_dir / "scenes"
    for fp in sorted(scene_dir.glob("*.txt")):
        for block in fp.read_text(encoding="utf-8").split("\n\n"):
            block = block.strip()
            if len(block) > 60 and "天桥在第八章，你现在只站在22:59里" not in block:
                # trim repetitive tail
                if block.count("故事下一段是天桥") > 0:
                    block = block[: block.index("故事下一段是天桥")].rstrip("，。") + "。"
                scenes.append(block)
    return scenes
