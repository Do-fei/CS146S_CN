def bank_for(chapter_file: str) -> list[str]:
    """Assemble full bank for one chapter."""
    cores = {
        "00-序.md": CORE_00,
        "01-发送失败.md": CORE_01,
        "02-空位.md": CORE_02,
        "03-赵宜家.md": CORE_03,
        "04-胡同.md": CORE_04,
        "05-第三夜.md": CORE_05,
        "06-胡同深.md": CORE_06,
        "07-便利店.md": CORE_07,
    }[chapter_file]
    seed = sum(ord(c) for c in chapter_file)
    ch_short = chapter_file.split("-")[1].split(".")[0]
    bank: list[str] = list(cores)
    bank.extend(_gen_school(seed, 35, ch_short))
    bank.extend(_gen_clue(seed, 25, ch_short))
    bank.extend(_gen_creepy(seed, 20, ch_short))
    bank.extend(_gen_sweet(seed, 20))
    return bank
