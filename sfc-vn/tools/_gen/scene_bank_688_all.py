def gen_scenes(ch_num: str, n: int, seed: int) -> list[str]:
    meta = CHAPTER_META.get(ch_num, ("深线", "十一点", []))
    theme, _subtitle, _hooks = meta
    rng = random.Random(seed)
    families = _families(theme)
    ch_i = int(ch_num) if ch_num.isdigit() else 0
    out: list[str] = []
    seen: set[str] = set()
    attempts = 0
    max_attempts = n * 4
    while len(out) < n and attempts < max_attempts:
        attempts += 1
        loc = rng.choice(PLACES)
        tm = rng.choice(TIMES)
        c = rng.choice(CLUES)
        b = rng.choice(BEATS)
        t = rng.choice(TWISTS)
        w = rng.choice(WEATHER)
        fn = rng.choice(families)
        cr = rng.choice(CROSS)
        para = fn(loc, c, b, t, tm, w, cr)
        if ch_i and ch_i % 3 == 0:
            para = para.replace("。", f"。{cr}", 1) if cr not in para else para
        key = para[:80]
        if key in seen:
            continue
        seen.add(key)
        out.append(para)
    return out


def bank_for(chapter_file: str) -> list[str]:
    ch_num = chapter_file.split("-")[0]
    seed = sum(ord(c) for c in chapter_file) + 68800
    bank: list[str] = list(HAND_688.get(ch_num, []))
    bank.extend(gen_scenes(ch_num, 1800, seed))
    return bank
