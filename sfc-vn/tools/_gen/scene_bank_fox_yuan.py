def _gen_rule_scene(_theme: str, rng: random.Random) -> str:
    rule = rng.choice(FOX_RULES)
    if rng.random() < 0.5:
        return rule + rng.choice(FUSION)
    return rule + rng.choice(YUAN_WIT)


def _gen_char_scene(rng: random.Random) -> str:
    who = rng.choice(list(CHAR_VOICE.keys()))
    base = rng.choice(CHAR_VOICE[who])
    loc, tm = rng.choice(PLACES), rng.choice(TIMES)
    return f"{loc}，{tm}。{base}"


def _gen_loc_scene(rng: random.Random) -> str:
    loc, tm = rng.choice(PLACES), rng.choice(TIMES)
    a, b = rng.sample(FOX_RULES + FUSION, 2)
    return f"{loc}，{tm}。{a}你摸袖口，褶还在——远瞳式安慰只有半句，狐尾式事实是：褶在，你还算同桌这边的人。{b}"


def gen_scenes(ch_num: str, n: int, seed: int) -> list[str]:
    theme = ch_num
    rng = random.Random(seed + int(ch_num) * 997 if ch_num.isdigit() else seed)
    out: list[str] = list(CH_HOOKS.get(ch_num, []))
    pools = FOX_RULES + YUAN_WIT + FUSION
    for v in CHAR_VOICE.values():
        pools.extend(v)
    seen: set[str] = set()
    attempts = 0
    while len(out) < n and attempts < n * 5:
        attempts += 1
        if rng.random() < 0.2:
            para = _gen_char_scene(rng)
        elif rng.random() < 0.35:
            para = _gen_loc_scene(rng)
        elif rng.random() < 0.5:
            para = _gen_rule_scene(theme, rng)
        else:
            para = rng.choice(pools)
            if rng.random() < 0.3:
                para = para + rng.choice(FUSION)
        key = para[:72]
        if key in seen:
            continue
        seen.add(key)
        out.append(para)
    return out


def bank_for(chapter_file: str) -> list[str]:
    ch_num = chapter_file.split("-")[0]
    seed = sum(ord(c) for c in chapter_file) + 880000
    return gen_scenes(ch_num, 2200, seed)
