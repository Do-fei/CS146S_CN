from pathlib import Path

NOVEL = Path(__file__).resolve().parents[2] / "docs" / "novel"
TARGET_MIN, TARGET_MAX = 16000, 18000


def write_chapter(name: str, body: str) -> int:
    path = NOVEL / name
    text = body.strip() + "\n"
    path.write_text(text, encoding="utf-8")
    n = len(text)
    status = "OK" if TARGET_MIN <= n <= TARGET_MAX else "WARN"
    print(f"{name}\t{n}\t{status}")
    return n


