def append_unique(path: Path, block: str):
    text = path.read_text(encoding="utf-8")
    for p in block.split("\n\n"):
        if len(p) > 40 and p.strip() in text:
            return False
    path.write_text(text.rstrip() + "\n\n" + block.strip() + "\n", encoding="utf-8")
    return True


def main():
    for name, (lo, hi) in TARGETS.items():
        path = ROOT / name
        if not path.exists():
            print(f"missing {name}")
            continue
        if name in EXP and EXP[name]:
            append_unique(path, EXP[name])
        n = len(path.read_text(encoding="utf-8"))
        status = "OK" if lo <= n <= hi else ("LOW" if n < lo else "HIGH")
        print(f"{name}\t{n}\t{status}\t({lo}-{hi})")


if __name__ == "__main__":
    main()
