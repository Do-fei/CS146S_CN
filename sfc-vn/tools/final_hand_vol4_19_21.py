def load_bank(name: str) -> list[str]:
    from importlib import import_module
    mod = import_module(name)
    bank = []
    for attr in sorted(dir(mod)):
        if attr.startswith("P") and attr[1:].isdigit() is False:
            val = getattr(mod, attr)
            if isinstance(val, list):
                bank.extend(val)
        elif attr.startswith("BANK"):
            bank.extend(getattr(mod, attr))
    if hasattr(mod, "BANK"):
        bank = list(mod.BANK)
    return bank


