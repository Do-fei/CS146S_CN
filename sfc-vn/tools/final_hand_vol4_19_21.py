def md5(s: str) -> str:
    return hashlib.md5(re.sub(r"\s+", "", s).encode()).hexdigest()


def existing_hashes(text: str) -> set[str]:
    hs: set[str] = set()
    for block in re.split(r"\n\n+", text.strip()):
        block = block.strip()
        if block and not block.startswith("#"):
            hs.add(md5(block))
    return hs


def insert_before(text: str, marker: str, paras: list[str]) -> str:
    seen = existing_hashes(text)
    new = [p for p in paras if md5(p) not in seen]
    if not new:
        return text
    idx = text.rfind(marker)
    block = "\n\n".join(new)
    if idx < 0:
        return text.rstrip() + "\n\n" + block + "\n"
    return text[:idx].rstrip() + "\n\n" + block + "\n\n" + text[idx:]


def pad_to(text: str, target: int, bank: list[str], marker: str) -> str:
    seen = existing_hashes(text)
    queue = [p for p in bank if md5(p) not in seen]
    i = 0
    while len(text) < target - 50 and i < len(queue):
        p = queue[i]
        text = insert_before(text, marker, [p])
        seen.add(md5(p))
        i += 1
    return text


