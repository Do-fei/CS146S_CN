def expand_section(text: str, header: str, addition: str) -> str:
    pattern = rf"(\*\*{re.escape(header)}\*\*\n\n)(.*?)(?=\n\n\*\*|\n\n---|\Z)"
    m = re.search(pattern, text, re.DOTALL)
    if not m:
        return text
    body = m.group(2).rstrip() + "\n\n" + addition.strip()
    replacement = m.group(1) + body
    return text[:m.start()] + replacement + text[m.end():]

