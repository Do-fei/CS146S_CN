def build_scenes(num: str) -> list[str]:
    if num == "19":
        return SCENES_19 + gen_19() + EXTRA_19
    if num == "20":
        return gen_20()
    if num == "21":
        return gen_21()
    if num == "22":
        return gen_22()
    if num == "23":
        return EXTRA_23_OPEN
    return []


def main() -> None:
    mapping = {
        "19-馆藏.md": CH19,
        "20-静音.md": CH20,
        "21-随河.md": CH21,
        "22-空白站.md": CH22,
        "23-八个早晨.md": CH23,
    }
    for fname, core in mapping.items():
        num = fname[:2]
        scenes = build_scenes(num)
        # For ch23, prepend core header paras then extras
        if num == "23":
            header = "\n\n".join(re.split(r"\n\n+", core.strip())[:5])
            body = pad(header, scenes, TARGET_HIGH)
        else:
            body = pad(core, scenes, TARGET_HIGH)
        path = ROOT / fname
        path.write_text(body, encoding="utf-8")
        loops = len(re.findall(r"卷四·", body))
        print(f"{fname}\t{len(body)}\tloops={loops}")


if __name__ == "__main__":
    main()
