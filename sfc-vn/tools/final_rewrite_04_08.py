def dedupe_paragraphs(text: str) -> str:
    """Remove duplicate paragraphs and HTML comment blocks."""
    text = re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)
    paras = []
    seen = set()
    for block in re.split(r"\n\s*\n", text.strip()):
        p = block.strip()
        if not p:
            continue
        # skip meta lines
        if re.search(r"第[五六七八]章写完|下一章|后面一章|后面章|M15|MEGA|BIG", p):
            continue
        if p in seen:
            continue
        seen.add(p)
        paras.append(p)
    return "\n\n".join(paras) + "\n"


def pad_chapter(text: str, target: int, extra_paras: list[str]) -> str:
    """Pad chapter to target length with unique paragraphs."""
    text = dedupe_paragraphs(text)
    for p in extra_paras:
        if len(text) >= target:
            break
        if p not in text:
            text = text.rstrip() + "\n\n" + p + "\n"
    return text


