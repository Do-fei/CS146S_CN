def main() -> None:
    bodies = load_rewrite_bodies()
    global_used: set = set()

    # Build chapters
    for name, base in bodies.items():
        text = build_chapter(name, base)
        text = pad_to_target(name, text, TARGETS[name], global_used)
        path = ROOT / name
        path.write_text(text.strip() + "\n", encoding="utf-8")

    total = project_total()
    # Expand 15-18 if project total short
    if total < PROJECT_MIN:
        extra_per = (PROJECT_MIN - total) // 4 + 500
        for name in ("15-停止.md", "16-爬回.md", "17-小的路.md", "18-漏句.md"):
            TARGETS[name] += extra_per
            text = (ROOT / name).read_text(encoding="utf-8")
            # Append unique one-off paragraphs from UNIQUES pool not yet used
            for p in UNIQUES.get(name, []):
                h = hashlib.md5(p.encode()).hexdigest()
                if h in global_used:
                    continue
                if len(text) >= TARGETS[name]:
                    break
                text = text + "\n\n" + p
                global_used.add(h)
            (ROOT / name).write_text(text.strip() + "\n", encoding="utf-8")
        total = project_total()

    sub = 0
    for name in bodies:
        text = (ROOT / name).read_text(encoding="utf-8")
        n = len(text)
        sub += n
        print(f"{name}\t{n}\t(target {TARGETS[name]})\tdup_paras={count_dupes(text)}")
    print(f"---\n15-23 subtotal\t{sub}")
    print(f"project total\t{total}")


if __name__ == "__main__":
    main()
