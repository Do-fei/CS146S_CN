def build_chapter(name: str, base: str) -> str:
    parts = [dedupe_paragraphs(base)]
    used = para_hash_set(parts[0])
    for p in UNIQUES.get(name, []):
        h = hashlib.md5(p.encode()).hexdigest()
        if h not in used:
            parts.append(p)
            used.add(h)
    return dedupe_paragraphs("\n\n".join(parts))


def count_dupes(text: str) -> int:
    paras = [p.strip() for p in re.split(r"\n\s*\n", text.strip()) if p.strip()]
    return len(paras) - len({hashlib.md5(p.encode()).hexdigest() for p in paras})


def project_total() -> int:
    return sum(len(p.read_text(encoding="utf-8")) for p in sorted(ROOT.glob("[0-9]*.md")))


