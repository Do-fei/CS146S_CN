def dedupe_paragraphs(text: str) -> str:
    seen = set()
    out = []
    for p in re.split(r"\n\s*\n", text.strip()):
        p = p.strip()
        if not p or p.startswith("<!--"):
            continue
        h = hashlib.md5(p.encode()).hexdigest()
        if h in seen:
            continue
        seen.add(h)
        out.append(p)
    return "\n\n".join(out)


def para_hash_set(text: str) -> set:
    return {
        hashlib.md5(p.strip().encode()).hexdigest()
        for p in re.split(r"\n\s*\n", text.strip())
        if p.strip()
    }


