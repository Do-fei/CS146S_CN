def append_or_replace(name: str, block: str, replace: bool = False):
    path = ROOT / name
    if replace:
        path.write_text(block.strip() + "\n", encoding="utf-8")
    else:
        content = path.read_text(encoding="utf-8")
        # dedupe: don't append if block already in file
