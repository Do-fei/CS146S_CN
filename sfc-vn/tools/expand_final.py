def main():
    for fn, text in APPENDS.items():
        path = ROOT / fn
        if not path.exists():
            print(f"skip missing {fn}")
            continue
        body = text.strip()
        if fn == "23-八个早晨.md":
            header = "# 第二十三章　八个早晨\n\n卷四不是岔路的攻略。是城在十一点之后，还亮着的别的窗口。八个早晨，八个并排，没有官方正确答案。\n\n"
