def clean_paragraphs(text: str, filename: str) -> str:
    lines = text.split("\n")
    out = []
    seen = set()
    for line in lines:
        stripped = line.strip()
        if not stripped:
            if out and out[-1] != "":
                out.append("")
            continue
        if any(p.search(stripped) for p in PADDING_PATTERNS):
            continue
        for pat in CROSS_CHAPTER_CUTS.get(filename, []):
            if pat.search(stripped):
                return "\n".join(out).rstrip() + "\n"
        # dedupe exact paragraphs (ignore title)
        if stripped.startswith("#"):
            out.append(line)
            continue
        key = stripped
        if key in seen:
            continue
        seen.add(key)
        out.append(line)
    return "\n".join(out).rstrip() + "\n"


def dedupe_near(text: str) -> str:
    """Remove paragraphs that are substring of a previous one."""
    paras = []
    for block in text.split("\n\n"):
        block = block.strip()
        if not block:
            continue
        if block.startswith("#"):
            paras.append(block)
            continue
        skip = False
        for i, prev in enumerate(paras):
            if prev.startswith("#"):
                continue
            if block in prev or prev in block:
                if len(block) <= len(prev):
                    skip = True
                    break
                paras[i] = block
                skip = True
                break
        if not skip:
            paras.append(block)
    return "\n\n".join(paras) + "\n"


def pad_to(text: str, target: int, extras: list[str]) -> str:
    body = text.rstrip()
    for para in extras:
        if len(body) >= target:
            break
        body = body + "\n\n" + para.strip()
    return body + "\n"


