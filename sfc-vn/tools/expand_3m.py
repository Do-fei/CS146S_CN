def process_expand(path: str, generators: list, seed: int) -> None:
    fp = ROOT / path
    raw = fp.read_text(encoding="utf-8") if fp.exists() else ""
    cleaned = dedupe_blocks(strip_loops(raw))
    # extract header + core (first ~40 paragraphs or until target core)
    parts = [p.strip() for p in cleaned.split("\n\n") if p.strip()]
    header = parts[0] if parts else f"# {path}"
    core_parts = []
    for p in parts[1:]:
        if any(
            x in p
            for x in (
                "我选——",
                "阿青在",
                "边看你",
                "详单又",
                "删除又",
                "第201遍",
                "按停止后第",
            )
        ) and len(p) > 400:
            continue
        core_parts.append(p)
        if sum(len(x) for x in core_parts) > 12000:
            break
    core = "\n\n".join(core_parts)
    text = build_until(header, core, generators, TARGET, seed)
    fp.write_text(text, encoding="utf-8")
    print(f"expand {path}\t{len(raw)} -> {len(text)}")


