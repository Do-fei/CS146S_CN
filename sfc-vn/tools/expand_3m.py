# ---------- strip helpers ----------

_LOOP_START = re.compile(
    r"^(第\d+遍翻簿|按停止后第\d+次|# 第二[四五]章|"
    r"阿青在(23:17|好友列表).*边看你|好友列表里删除又|详单又|"
    r"23:17里详单又|你查自己手机应用使用时间，23:17显示)"
)


def strip_loops(text: str) -> str:
    lines = text.splitlines()
    out: list[str] = []
    seen_header = False
    skip = False
    for line in lines:
        if line.startswith("# 第"):
            if seen_header:
                skip = True
                continue
            seen_header = True
        if _LOOP_START.match(line.strip()):
            skip = True
            continue
        if skip and line.strip() == "":
            continue
        if skip and not line.startswith("#"):
            if _LOOP_START.match(line.strip()):
                continue
            # end skip on substantial non-loop paragraph
            if len(line) > 80 and "我选——" not in line[:40]:
                skip = False
            else:
                continue
        skip = False
        out.append(line)
    return "\n".join(out).strip() + "\n"


def dedupe_blocks(text: str) -> str:
    parts: list[str] = []
    seen: set[str] = set()
    for block in re.split(r"\n\n+", text.strip()):
        block = block.strip()
        if not block:
            continue
        if block.startswith("#"):
            parts.append(block)
            continue
        key = hashlib.md5(re.sub(r"\s+", "", block).encode()).hexdigest()
        if key in seen:
            continue
        seen.add(key)
        parts.append(block)
    return "\n\n".join(parts) + "\n"


def build_until(
    header: str,
    core: str,
    generators: list[Callable[[int], str]],
    target: int = TARGET,
    seed: int = 0,
) -> str:
    blocks = [header.strip(), core.strip()]
    seen: set[str] = set()
    for b in blocks:
        seen.add(hashlib.md5(re.sub(r"\s+", "", b).encode()).hexdigest())
    i = 0
    while sum(len(b) for b in blocks) < target:
        gen = generators[i % len(generators)]
        block = gen(i + seed)
        key = hashlib.md5(re.sub(r"\s+", "", block).encode()).hexdigest()
        if key not in seen:
            seen.add(key)
            blocks.append(block)
        i += 1
        if i > 25000:
            break
    text = "\n\n".join(blocks)
    while len(text) > target + 1500 and len(blocks) > 8:
        blocks.pop(-1)
        text = "\n\n".join(blocks)
    return text + "\n"


