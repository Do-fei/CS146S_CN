def join(*parts: str) -> str:
    return "\n\n".join(p.strip() for p in parts if p.strip())


def pad_scenes(body: str, extras: list[str], target: int) -> str:
    """Append non-duplicate extra scenes until near target."""
    out = body
    for ex in extras:
        if len(out) >= target * 0.96:
            break
        if ex.strip() not in out:
            out = out + "\n\n" + ex.strip()
    return out


