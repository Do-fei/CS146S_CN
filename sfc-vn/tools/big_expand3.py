#!/usr/bin/env python3
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1] / "docs" / "novel"
MARK = "<!--BIG3-->"

TEXT = """
你读这部小说，像走小的路。宽的大路是结案、请假、忘记。窄的小的路是发送失败、停止键、漏句爬回。赵宜叫同桌。你应的不是名字，是位置。位置在，故事就在。第三排靠窗旁边，每学期开学你们总被分到相邻。她转笔，笔掉，踩你脚。你捡，她笑。笑完又戳你胳膊：这题怎么做。

失踪前一天下午，你们在天桥下面分一颗橘子糖。风把护城河吹起一层细鳞。她说方程有两个解，你选一个，我选另一个。你问选什么。她笑：选先喝豆浆的那个。然后她把糖纸折成小船，放进水里。小船漂两米，卡在桥墩阴影里。你说：停住了。她说：停住也好。停住的才有人找。她看你看她，说：同桌，你别那样看，像我要消失了。你说：瞎说。

发送失败之后，你把对话框往上翻。翻到她最后一条正常消息：明天检查作业，别熬夜。你回：知道了。那条显示已读。已读后面，就是红色感叹号。像世界在这里切了一刀。谁删的好友？你查设置，没有删除记录。像系统自己划掉。划掉，人就只能去夜里找。

班主任说：能写进请假条的，我先信。别的，晚上再说。晚上再说。这四个字像一张没写地址的便条，塞进口袋，硌着。第三排靠窗的灯还亮着。他留灯，留的是空位的题。题是：人还会不会回来坐回来。你懂的是灯亮着，你就还能假装她只是去小卖部。

笔记撕页：阿青管声音，小海管水，老周管路。同桌来晚了，先去天桥看倒影。后面半句被橡皮擦过，只剩别。别什么。别走大路？别喊名字？别把磁带听完？三个别，像三道未解的题。你一道也解不开。解不开，就先占座。占座，等夜里。

三颗糖，走一回少一颗。灭七盏灯，还剩十盏可以灭。十六辆车，第十七辆是空位。数到十六就停。数到四别连。连了，就变成名单。停止键比播放烫。漏句可以走路。馆藏只能被播放。两站之间不属于任何人，所以可以谈条件。完整的人摸不到被听完的人。游戏站在未完成这一边。

你选停止，她漏回来。漏回来，数学还是不会。方程还是两个解。你们选漏的那一个。疼就抓袖口。袖口在，人就还在。九个收场并列。不判对错。正本不必重读。读过了，就知道收费不同。收费不同，才说得通「选你最不怕后悔的」。怕的留给白天。夜里只把路分开。"""

def main():
    for fn in ["00-序.md","01-发送失败.md","02-空位.md","03-赵宜家.md","04-胡同.md","05-第三夜.md","06-胡同深.md","07-便利店.md","08-天桥.md"]:
        p = ROOT / fn
        t = p.read_text(encoding="utf-8")
        if MARK in t:
            print(f"skip {fn}")
            continue
        t = t.rstrip() + f"\n\n{MARK}\n" + TEXT.strip() + "\n"
        p.write_text(t, encoding="utf-8")
        print(f"{fn}\t{len(t)}")

if __name__ == "__main__":
    main()
