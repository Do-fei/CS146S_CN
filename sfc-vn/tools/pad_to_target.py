# Chapter-specific assignments (indices into BANK)
ASSIGN = {
    "00-序.md": list(range(0, 8)),
    "01-发送失败.md": list(range(8, 28)),
    "02-空位.md": list(range(28, 42)),
    "03-赵宜家.md": list(range(42, 52)),
    "04-胡同.md": list(range(52, 68)),
    "05-第三夜.md": list(range(68, 78)),
    "06-胡同深.md": list(range(78, 88)),
    "07-便利店.md": list(range(88, len(BANK))),
}


def main():
    used = set()
    for name, target in TARGETS.items():
        if name == "00-序.md":
            continue
        path = NOVEL / name
        body = path.read_text(encoding="utf-8").strip()
        idxs = ASSIGN.get(name, [])
        for i in idxs:
            if i >= len(BANK):
                continue
            para = BANK[i]
            if para in body:
                continue
            if len(body) >= target * 0.98:
                break
            body += "\n\n" + para
            used.add(i)
        # if still short, pull any unused bank lines
        if len(body) < target * 0.96:
            for i, para in enumerate(BANK):
                if i in used or para in body:
                    continue
                if len(body) >= target * 0.98:
                    break
                body += "\n\n" + para
        path.write_text(body.strip() + "\n", encoding="utf-8")
        print(f"{name}\t{len(body.strip())}\t(target {target})")


if __name__ == "__main__":
    main()
