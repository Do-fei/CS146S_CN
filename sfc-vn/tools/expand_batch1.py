def main():
    for fn, (marker, text) in INSERTS.items():
        path = ROOT / fn
        content = path.read_text(encoding="utf-8")
        if text.strip() in content:
            print(f"skip {fn} (already expanded)")
            continue
        if marker not in content:
            print(f"WARN {fn}: marker not found")
            continue
        content = content.replace(marker, marker + text, 1)
        path.write_text(content, encoding="utf-8")
        print(f"expanded {fn} (+{len(text)} chars)")

if __name__ == "__main__":
    main()
