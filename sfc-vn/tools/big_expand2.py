#!/usr/bin/env python3
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1] / "docs" / "novel"
MARK = "<!--BIG2-->"

TEXT = """
二层那会儿，你们总被分到第三排靠窗。她转笔，转掉了就踩你脚，让你捡。你捡，她谢，谢完又戳你胳膊：这题怎么做。你讲一遍，她听一半，另一半去画小人。小人在卷子上举牌子：同桌加油。你说幼稚。她说：幼稚才像人。幼稚的人，夜里比较不容易被写成条目。

有一回值日，你擦黑板，她洗抹布。水凉，她把手在衣摆上蹭，蹭完又蹭你袖口，像开玩笑。你躲，她说：同桌互助。你笑。笑完继续擦。擦到一半，她在下面排值日歌，跑调，跑调也认真。你当时觉得日子会一直这样：黑板、抹布、跑调、踩脚。发送失败之后，你仍做这些小事。擦黑板时多留一块没擦，像留空位。洗抹布时水仍凉，凉得像确认她不在。你不再排值日歌。跑调需要两个人，一个唱，一个笑。

赵宜妈妈坐在女儿位子上，大衣没脱，问：宜宜有没有跟你说要去哪儿。你摇头。她把「晚上豆浆，我请」揭起来，又贴回去。动作很轻，像怕把字蹭掉。请是承诺。承诺在，你就不能当它已经失效。失效，像大路。大路会把承诺写成请假条。你不写。你把豆浆留到结皮。结皮像时间。时间慢，你就还能假装她只是去小卖部。

警察倒杯热水：记录里她是自行离开。笔记推过去。他看很久，没收：这些名字白天问不到。他压低声音：十一点以后，别答应水里的人，别答应倒影，别把一整盘磁带听完。说多了没用。你按她短信走。我们在大路上等。大路等，小的路找。你选小的。小的，从发送失败开始，从红色感叹号开始，从「晚上豆浆，我请」那行字开始。

天桥上，护城河黑。桥灯橙。积水平。你蹲过。倒影里赵宜晃橘子。口型：别走大路。你咽回应。先别喊名字。你喊了同桌一声嗯，又把后半句咽回去。雨丝细了。该选路。你跟上阿青。西单。倒带馆。磁带。停止键。你还不按。按了，是后面的章。现在，你只站桥。站桥，像还某种同桌的约。

便利店的钟停在22:59。秒针抖，不跳23:00。你问：什么馅。店员说鸡蛋沙拉。标签写赵宜的也是。你愣。他说：别信标签，信口袋。口袋有糖，说明你是来找人的。你买便当。袋子发热。像有人刚从教室跑出来。监控跳一帧白天教室。空位。桌角请还在。人不在。请还在，你就还不能把结皮倒掉。

胡同路灯一盏盏灭。你数到第七盏，身后南横街全黑。不是停电。是光在退。你停数。第八盏灭时你没看。砖缝渗水往前流。收音机念崇文宣武。修鞋铺指前面：胡同。就两个字。你进胡同了。灯开始灭。第四章止于这里。第三夜写湿鞋和镜里慢半拍。胡同深写深。便利店写22:59。天桥写选阿青。正本，从发送失败走到这里。"""

def main():
    for fn in ["00-序.md","01-发送失败.md","02-空位.md","03-赵宜家.md","04-胡同.md","05-第三夜.md","06-胡同深.md","07-便利店.md","08-天桥.md"]:
        p = ROOT / fn
        t = p.read_text(encoding="utf-8")
        if MARK in t:
            print(f"skip {fn}")
            continue
        t = t.rstrip() + f"\n\n{MARK}\n" + TEXT.strip() + "\n"
        p.write_text(t, encoding="utf-8")
        print(f"{fn}\t{len(t)}")

if __name__ == "__main__":
    main()
