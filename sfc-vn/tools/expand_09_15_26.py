def main() -> None:
    spec = importlib.util.spec_from_file_location("clean", TOOLS / "clean_novel_ai.py")
    clean = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(clean)

    # Generate remaining banks inline if scene files missing
    _generate_all_banks()

    for fname, target in TARGETS.items():
        path = ROOT / fname
        if path.exists():
            text = path.read_text(encoding="utf-8")
            text = strip_leaked(text)
        else:
            title = fname.split("-", 1)[1].replace(".md", "")
            num = fname.split("-")[0]
            text = f"# 第{num.lstrip('0') or '0'}章　{title}\n\n"

        bank = BANKS.get(fname, [])
        text = pad_to(text, target, bank)
        text = clean.clean_text(text)
        # final pad if clean removed dupes
        if len(text) < target:
            text = pad_to(text, target, bank)
        path.write_text(text, encoding="utf-8")
        print(f"{fname}\t{len(text)}")

    subprocess.run(["python3", str(TOOLS / "count_novel.py")], check=True)


