def _load_bank(name: str) -> list[str]:
    p = TOOLS / "scenes" / f"{name}.txt"
    if p.exists():
        return [b.strip() for b in p.read_text(encoding="utf-8").split("\n\n") if b.strip()]
    return []


def md5(s: str) -> str:
    return hashlib.md5(re.sub(r"\s+", "", s).encode()).hexdigest()


def existing_hashes(text: str) -> set[str]:
    hs: set[str] = set()
    for block in re.split(r"\n\n+", text.strip()):
        block = block.strip()
        if block and not block.startswith("#"):
            hs.add(md5(block))
    return hs


def strip_leaked(text: str) -> str:
    for pat in STRIP_PATTERNS:
        text = re.sub(pat, "", text, flags=re.DOTALL)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip() + "\n"


def pad_to(text: str, target: int, bank: list[str]) -> str:
    seen = existing_hashes(text)
    queue = [p for p in bank if md5(p) not in seen]
    i = 0
    while len(text) < target and i < len(queue):
        p = queue[i]
        text = text.rstrip() + "\n\n" + p + "\n"
        seen.add(md5(p))
        i += 1
    # cycle bank with suffix if still short
    cycle = 0
    while len(text) < target and queue:
        for p in queue:
            suffix = f"（续{cycle}）" if cycle else ""
            block = p + suffix
            if md5(block) in seen:
                continue
            text = text.rstrip() + "\n\n" + block + "\n"
            seen.add(md5(block))
            if len(text) >= target:
                break
        cycle += 1
        if cycle > 50:
            break
    return text


