def _combo_scenes(
    acts: list[str],
    rels: list[str],
    closers: list[str],
    n: int,
    offset: int = 0,
) -> list[str]:
    """Combinatorial unique paragraphs — varied closers, no repeated suffix block."""
    out: list[str] = []
    for i in range(n):
        loc = LOCS[(i + offset) % len(LOCS)]
        tm = TIMES[(i * 3 + offset) % len(TIMES)]
        w = WEATHER[(i * 5 + offset) % len(WEATHER)]
        act = acts[(i * 7 + offset) % len(acts)]
        rel = rels[(i * 11 + offset) % len(rels)]
        obj = OBJS[(i * 13 + offset) % len(OBJS)]
        close = closers[(i * 17 + offset) % len(closers)]
        out.append(
            f"{tm}，{loc}，{w}，{act}，{rel}，"
            f"你把{obj}压进数学书，书合拢像把疑点留在会翻页的地方，{close}。"
        )
    return out


def _build(core: str, scenes: list[str], close: str) -> str:
    """Pad core body, then append closing paragraph last."""
    body = _pad(core, scenes, TARGET - len(close) - 4)
    if not body.rstrip().endswith("。"):
        body = body.rstrip() + "\n"
    return body.rstrip() + "\n\n" + close + "\n"


