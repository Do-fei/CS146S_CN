def trim_to_target(text: str) -> str:
    if len(text) <= TARGET + TOLERANCE:
        return text
    paras = text.split("\n\n")
    title = paras[0] if paras[0].startswith("#") else ""
    body = paras[1:] if title else paras
    # keep title + as many paragraphs from start until near target
    out = [title] if title else []
    n = len(title) + 2 if title else 0
    for p in body:
        if n + len(p) + 2 > TARGET + 100 and len(out) > (1 if title else 0) + 5:
            break
        out.append(p)
        n += len(p) + 2
    return "\n\n".join(x for x in out if x) + "\n"


