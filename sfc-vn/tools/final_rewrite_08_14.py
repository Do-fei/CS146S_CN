def is_telegraphic(p: str) -> bool:
    """Flag 电报体: many clauses ≤8 chars."""
    parts = re.split(r"[，。；！？]", p)
    parts = [x.strip() for x in parts if len(x.strip()) > 1]
    if len(parts) < 4:
        return False
    short = sum(1 for x in parts if len(x) <= 8)
    return short / len(parts) > 0.55


def dedupe_file(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    paras = [p.strip() for p in text.split("\n\n") if p.strip()]
    title = paras[0] if paras and paras[0].startswith("#") else ""
    body = paras[1:] if title else paras
    seen: set[str] = set()
    kept: list[str] = []
    for p in body:
        if META_RE.match(p) or len(p) < 45:
            continue
        if is_telegraphic(p):
            continue
        if p in seen:
            continue
        seen.add(p)
        kept.append(p)
    return title + "\n\n" + "\n\n".join(kept) + "\n" if title else "\n\n".join(kept) + "\n"


def pad_to_target(text: str, extras: list[str]) -> str:
    text = text.rstrip() + "\n"
    used = set(p.strip() for p in text.split("\n\n") if p.strip())
    rounds = 0
    while len(text) < TARGET - TOLERANCE and rounds < 30:
        added = 0
        for p in extras:
            if len(text) >= TARGET - 50:
                break
            p = p.strip()
            if not p or p in used:
                continue
            text += "\n\n" + p + "\n"
            used.add(p)
            added += 1
        if added == 0:
            break
        rounds += 1
    return text


