def dedupe_blocks(text: str) -> str:
    parts: list[str] = []
    seen: set[str] = set()
    for block in re.split(r"\n\n+", text.strip()):
        block = block.strip()
        if not block:
            continue
        if block.startswith("#"):
            parts.append(block)
            continue
        key = hashlib.md5(re.sub(r"\s+", "", block).encode()).hexdigest()
        if key in seen:
            continue
        seen.add(key)
        parts.append(block)
    return "\n\n".join(parts) + "\n"


def build_until(target: int, header: str, generators: list, seed: int = 0) -> str:
    blocks = [header.strip()]
    seen: set[str] = set()
    i = 0
    while sum(len(b) for b in blocks) < target:
        gen = generators[i % len(generators)]
        block = gen(i + seed)
        key = hashlib.md5(re.sub(r"\s+", "", block).encode()).hexdigest()
        if key not in seen:
            seen.add(key)
            blocks.append(block)
        i += 1
        if i > 12000:
            break
    text = "\n\n".join(blocks)
    if len(text) > target + 2000:
        while len(text) > target and len(blocks) > 5:
            blocks.pop(-2)
            text = "\n\n".join(blocks)
    return text + "\n"


