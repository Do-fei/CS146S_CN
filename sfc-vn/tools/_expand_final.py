def pad_to(text: str, target: int, extras: list[str]) -> str:
    """Append unique paragraphs until near target (avoid over by checking)."""
    used = set()
    body = text.rstrip()
    for para in extras:
        if para in used:
            continue
        if len(body) >= target - 50:
            break
        used.add(para)
        body += "\n\n" + para
    return body + "\n"


