def main():
    for fn, text in APPENDS.items():
        path = ROOT / fn
        content = path.read_text(encoding="utf-8")
        tag = f"<!--EXPAND:{fn}-->"
        if tag in content:
            print(f"skip {fn}")
            continue
        path.write_text(content.rstrip() + "\n\n" + tag + "\n" + text.strip() + "\n", encoding="utf-8")
        print(f"append {fn} (+{len(text)} chars)")

if __name__ == "__main__":
    main()
