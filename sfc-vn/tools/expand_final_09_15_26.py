def expand_chapter(fname: str, target: int, clean) -> None:
    path = ROOT / fname
    if fname == "26-磁带背面.md":
        text = ""
    elif path.exists():
        text = path.read_text(encoding="utf-8")
        text = clean.clean_text(text)
    else:
        text = ""

    idx = 0
    gen_fn, core = GEN_MAP[fname]
    while len(text) < target:
        batch = list(core) + gen_fn(80, idx)
        before = len(text)
        text = pad_unique(text, target, batch)
        idx += 80
        if len(text) == before and idx > 800:
            break
        if idx > 1200:
            break

    text = clean.clean_text(text)
    path.write_text(text, encoding="utf-8")
    print(f"{fname}\t{len(text)}")


def clean_targets(clean) -> None:
    for fname in TARGETS:
        path = ROOT / fname
        if not path.exists():
            continue
        raw = path.read_text(encoding="utf-8")
        cleaned = clean.clean_text(raw)
        path.write_text(cleaned, encoding="utf-8")
        print(f"clean {fname}\t{len(raw)} -> {len(cleaned)}")


def main() -> None:
    spec = importlib.util.spec_from_file_location("clean", TOOLS / "clean_novel_ai.py")
    clean = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(clean)

    for fname, target in TARGETS.items():
        expand_chapter(fname, target, clean)

    clean_targets(clean)
    subprocess.run(["python3", str(TOOLS / "count_novel.py")], check=True)


if __name__ == "__main__":
    main()
