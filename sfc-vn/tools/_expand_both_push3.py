    p23.write_text(t23, encoding="utf-8")
    print(f"ch23: {len(t23)}")
    for h in CH23:
        m = re.search(rf"\*\*{re.escape(h)}\*\*\n\n(.*?)(?=\n\n\*\*|\n\n---|\Z)", t23, re.DOTALL)
        if m:
            print(f"  {h}: {len(m.group(1).strip())}")

