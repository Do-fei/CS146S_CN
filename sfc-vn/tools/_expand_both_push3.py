def expand(text, header, add):
    pat = rf"(\*\*{re.escape(header)}\*\*\n\n)(.*?)(?=\n\n\*\*|\n\n---|\Z)"
    m = re.search(pat, text, re.DOTALL)
    if not m:
        return text
    body = m.group(2).rstrip() + "\n\n" + add.strip()
    return text[:m.start()] + m.group(1) + body + text[m.end():]

