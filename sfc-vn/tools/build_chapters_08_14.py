def assemble(title: str, sections: list[str]) -> str:
    text = title + "\n\n" + "\n\n".join(s.strip() for s in sections if s.strip())
    return text + "\n"


def trim_or_report(name: str, text: str) -> int:
    n = len(text)
    path = ROOT / name
    path.write_text(text, encoding="utf-8")
    return n


