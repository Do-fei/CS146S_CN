def _dedupe_blocks(text: str) -> str:
    parts: list[str] = []
    seen: set[str] = set()
    for block in re.split(r"\n\n+", text.strip()):
        block = block.strip()
        if not block:
            continue
        if block.startswith("#"):
            parts.append(block)
            continue
        key = hashlib.md5(re.sub(r"\s+", "", block).encode()).hexdigest()
        if key in seen:
            continue
        seen.add(key)
        parts.append(block)
    return "\n\n".join(parts) + "\n"


def pad(core: str, extras: list[str], target: int) -> str:
    body = _dedupe_blocks(core.strip())
    seen: set[str] = set()
    for block in re.split(r"\n\n+", body.strip()):
        if block.strip():
            seen.add(hashlib.md5(re.sub(r"\s+", "", block).encode()).hexdigest())
    idx = 0
    attempts = 0
    while len(body) < target - 80 and attempts < len(extras) * 3:
        para = extras[idx % len(extras)]
        idx += 1
        attempts += 1
        key = hashlib.md5(re.sub(r"\s+", "", para).encode()).hexdigest()
        if key in seen:
            continue
        seen.add(key)
        body = body.rstrip() + "\n\n" + para
    return body + "\n"


