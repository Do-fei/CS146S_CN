    tags = ["并排", "省略号", "保管", "静音", "随河", "空白票", "袖口", "漏句"]
    for i in range(n):
        s = base[i % len(base)]
        tag = tags[i % len(tags)]
        out.append(f"{s} 大韦，第{i + 1}次守{tag}，不重选，不念省略号。（{i}）")
    return out


