def project_total() -> int:
    total = 0
    for path in sorted(ROOT.glob("[0-9]*.md")):
        total += len(path.read_text(encoding="utf-8"))
    return total


def main() -> None:
    target = TARGET_HIGH

    for name, (core, scenes) in CHAPTERS.items():
        text = pad(core, scenes, target)
        path = ROOT / name
        path.write_text(text, encoding="utf-8")
        print(f"{name}\t{len(text)}")

    print(f"---\ntotal\t{project_total()}")


if __name__ == "__main__":
    main()
