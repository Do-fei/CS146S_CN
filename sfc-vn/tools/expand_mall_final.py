def md5(s: str) -> str:
    return hashlib.md5(re.sub(r"\s+", "", s).encode()).hexdigest()


def preprocess(text: str, aggressive: bool = False) -> str:
    if aggressive:
        for pat in STRIP_PATTERNS:
            text = re.sub(pat, "", text, flags=re.DOTALL)
    kept: list[str] = []
    for block in re.split(r"\n\n+", text.strip()):
        block = block.strip()
        if not block:
            continue
        if re.match(r"第\d+次", block):
            continue
        if any(m in block for m in META_SUBSTR):
            continue
        kept.append(block)
    return "\n\n".join(kept) + "\n"


def existing_hashes(text: str) -> set[str]:
    hs: set[str] = set()
    for block in re.split(r"\n\n+", text.strip()):
        block = block.strip()
        if block and not block.startswith("#"):
            hs.add(md5(block))
    return hs


def pad_unique(text: str, target: int, bank: list[str]) -> str:
    seen = existing_hashes(text)
    for p in bank:
        if len(text) >= target:
            break
        p = p.strip()
        if not p or md5(p) in seen:
            continue
        text = text.rstrip() + "\n\n" + p + "\n"
        seen.add(md5(p))
    return text


