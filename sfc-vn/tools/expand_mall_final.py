def expand_chapter(fname: str, target: int, clean) -> None:
    path = ROOT / fname
    if fname == "26-磁带背面.md":
        text = ""
    elif path.exists():
        aggressive = fname == "09-西单.md"
        text = preprocess(path.read_text(encoding="utf-8"), aggressive=aggressive)
        text = clean.clean_text(text)
    else:
        text = ""

    core, gen_fn = GEN_MAP[fname]
    start = 0
    if not text.strip() and core:
        text = pad_unique(text, target, core)
    stall = 0
    while len(text) < target and start < 4000:
        before = len(text)
        text = pad_unique(text, target, gen_fn(50, start))
        start += 50
        if len(text) == before:
            stall += 1
            start += 200
        else:
            stall = 0
        if stall >= 5:
            start += 1000
            stall = 0

    text = clean.clean_text(text)
    path.write_text(text, encoding="utf-8")
    print(f"{fname}\t{len(text)}")


def main() -> None:
    spec = importlib.util.spec_from_file_location("clean", TOOLS / "clean_novel_ai.py")
    clean = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(clean)

    for fname, target in TARGETS.items():
        expand_chapter(fname, target, clean)

    for fname in TARGETS:
        path = ROOT / fname
        raw = path.read_text(encoding="utf-8")
        cleaned = clean.clean_text(raw)
        path.write_text(cleaned, encoding="utf-8")

    subprocess.run(["python3", str(TOOLS / "count_novel.py")], check=True)


