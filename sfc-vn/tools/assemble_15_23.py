def git_head(name: str, n: int) -> str:
    path = f"{REPO}/{name}"
    out = subprocess.check_output(["git", "show", path], cwd=ROOT.parent, text=True, errors="replace")
    return "\n".join(out.splitlines()[:n]).strip()


def dedupe_paragraphs(text: str) -> str:
    seen = set()
    out = []
    for p in text.split("\n\n"):
        p = p.strip()
        if not p or p.startswith("<!--"):
            continue
        h = hashlib.md5(p.encode()).hexdigest()
        if h in seen:
            continue
        seen.add(h)
        out.append(p)
    return "\n\n".join(out)


def count_dupes(text: str) -> int:
    paras = [p.strip() for p in text.split("\n\n") if p.strip()]
    return len(paras) - len({hashlib.md5(p.encode()).hexdigest() for p in paras})


