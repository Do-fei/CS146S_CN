def build_chapter(name: str) -> str:
    core = dedupe_paragraphs(git_head(name, CUTS[name]))
    parts = [core]
    core_hashes = {hashlib.md5(p.encode()).hexdigest() for p in core.split("\n\n") if p.strip()}
    for p in EXPAND_HAND.get(name, []):
        h = hashlib.md5(p.encode()).hexdigest()
        if h not in core_hashes:
            parts.append(p)
            core_hashes.add(h)

    target = TARGETS[name]
    scene_fn = {
        "15-停止.md": scene_main_15,
        "16-爬回.md": scene_main_16,
        "17-小的路.md": scene_main_17,
        "18-漏句.md": scene_main_18,
        "19-馆藏.md": scene_cold_19,
        "20-静音.md": scene_cold_20,
        "21-随河.md": scene_cold_21,
        "22-空白站.md": scene_cold_22,
        "23-八个早晨.md": scene_cold_23,
    }.get(name)

    i = 0
    dawei_count = 0
    while len("\n\n".join(parts)) < target:
        if scene_fn and i < 120:
            p = scene_fn(i)
        else:
            p = gen_prose(name, i)
        h = hashlib.md5(p.encode()).hexdigest()
        if h not in core_hashes:
            parts.append(p)
            core_hashes.add(h)
        if (
            name in ("15-停止.md", "16-爬回.md", "17-小的路.md", "18-漏句.md")
            and i % 45 == 20
            and dawei_count < 2
        ):
            p2 = dawei_beat(dawei_count)
            h2 = hashlib.md5(p2.encode()).hexdigest()
            if h2 not in core_hashes:
                parts.append(p2)
                core_hashes.add(h2)
                dawei_count += 1
        i += 1
        if i > 2500:
            break

    return dedupe_paragraphs("\n\n".join(parts))


def project_total() -> int:
    return sum(len(p.read_text(encoding="utf-8")) for p in sorted(ROOT.glob("[0-9]*.md")))


