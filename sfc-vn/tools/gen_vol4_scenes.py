def append(path: str, scenes: list[str]) -> None:
    p = ROOT / path
    existing = p.read_text(encoding="utf-8") if p.exists() else ""
    blocks = [b.strip() for b in existing.split("\n---\n") if b.strip()]
    blocks.extend(scenes)
    p.write_text("\n---\n".join(blocks), encoding="utf-8")
    print(path, len(blocks), sum(len(b) for b in blocks))


