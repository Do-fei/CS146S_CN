def deslop_export(text: str) -> str:
    missing = [old for old, _new in REPLACEMENTS if old not in text]
    if missing:
        preview = "\n".join(f"- {item[:80]}" for item in missing[:12])
        raise RuntimeError(
            f"deslop 有 {len(missing)} 条原文对不上，先核对游戏正文：\n{preview}"
        )
    for old, new in REPLACEMENTS:
        text = text.replace(old, new)
    leftover = text.count("——")
    # 章节分隔线是 markdown 的 ---，正文破折号应已清空。
    if leftover:
        raise RuntimeError(f"阅读稿还剩 {leftover} 处破折号")
    return text
