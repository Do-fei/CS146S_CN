def clean_text(text: str, fname: str) -> str:
    text = re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)
    lines = text.split("\n")
    title = lines[0] if lines and lines[0].startswith("#") else ""
    body = text[len(title):].lstrip("\n") if title else text
    paras = [p.strip() for p in re.split(r"\n\s*\n", body) if p.strip()]
    seen = set()
    out = []
    skip_patterns = [
        r"第[五六七八]章写完",
        r"下一章",
        r"后面一章",
        r"后面章",
        r"第五章写完",
        r"第六章走到",
        r"第七章写完",
        r"第八章写完",
        r"正本从发送失败",
        r"后面倒带馆",
        r"天桥在第八章",
        r"天桥在后面",
        r"第三夜会写",
        r"胡同深会写",
        r"便利店会写",
        r"天桥会写",
        r"第四章止于",
        r"你已在路上。正本",
    ]
    for p in paras:
        if p.startswith("---"):
            continue
        if any(re.search(pat, p) for pat in skip_patterns):
            continue
        key = re.sub(r"\s+", "", p)
        if len(key) >= 20:
            sig = key[:80]
            if sig in seen:
                continue
            seen.add(sig)
        out.append(p)
    if title:
        return title + "\n\n" + "\n\n".join(out) + "\n"
    return "\n\n".join(out) + "\n"


def pad_to_target(fname: str, target: int):
    path = NOVEL / fname
    text = path.read_text(encoding="utf-8")
    pool = POOL.get(fname, [])
    i = 0
    while len(text) < target and pool:
        p = pool[i % len(pool)]
        i += 1
        if p not in text:
            text = text.rstrip() + "\n\n" + p + "\n"
        if i > len(pool) * 3:
            break
    path.write_text(text, encoding="utf-8")
    return len(text)


