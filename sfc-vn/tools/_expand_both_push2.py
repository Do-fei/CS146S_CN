def expand_ch23(text: str, header: str, addition: str) -> str:
    pattern = rf"(\*\*{re.escape(header)}\*\*\n\n)(.*?)(?=\n\n\*\*|\n\n---|\Z)"
    m = re.search(pattern, text, re.DOTALL)
    if not m:
        return text
    body = m.group(2).rstrip() + "\n\n" + addition.strip()
    return text[:m.start()] + m.group(1) + body + text[m.end():]

def main():
    p22 = ROOT / "22-空白站.md"
    t22 = p22.read_text(encoding="utf-8")
    t22 = t22.replace("写 short", "写短")
    if CH22_EXTRA.strip() not in t22:
        t22 = t22.rstrip() + "\n" + CH22_EXTRA
    p22.write_text(t22, encoding="utf-8")
    print(f"ch22: {len(t22)}")

    p23 = ROOT / "23-八个早晨.md"
    t23 = p23.read_text(encoding="utf-8")
    for h, a in CH23_ADD.items():
        t23 = expand_ch23(t23, h, a)
    p23.write_text(t23, encoding="utf-8")
    print(f"ch23: {len(t23)}")
    for h in CH23_ADD:
        m = re.search(rf"\*\*{re.escape(h)}\*\*\n\n(.*?)(?=\n\n\*\*|\n\n---|\Z)", t23, re.DOTALL)
        if m:
            print(f"  {h}: {len(m.group(1).strip())}")

if __name__ == "__main__":
    main()
