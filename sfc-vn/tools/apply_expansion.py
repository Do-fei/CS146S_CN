def _md5(s: str) -> str:
    return hashlib.md5(re.sub(r"\s+", "", s).encode()).hexdigest()


def _existing_hashes(text: str) -> set[str]:
    hs: set[str] = set()
    for block in re.split(r"\n\n+", text.strip()):
        block = block.strip()
        if block and not block.startswith("#"):
            hs.add(_md5(block))
    return hs


def _insert_before_marker(text: str, marker: str, paras: list[str]) -> str:
    idx = text.rfind(marker)
    if idx < 0:
        return text.rstrip() + "\n\n" + "\n\n".join(paras) + "\n"
    before = text[:idx].rstrip()
    after = text[idx:]
    return before + "\n\n" + "\n\n".join(paras) + "\n\n" + after


def expand_chapter(path: Path, paras: list[str], target: int, end_marker: str | None = None) -> None:
    text = path.read_text(encoding="utf-8")
    seen = _existing_hashes(text)
    to_add: list[str] = []
    for p in paras:
        h = _md5(p)
        if h not in seen:
            to_add.append(p)
            seen.add(h)
    i = 0
    while len(text) + sum(len(p) + 2 for p in to_add) < target and i < len(paras):
        p = paras[i % len(paras)]
        h = _md5(p)
        if h not in seen:
            to_add.append(p)
            seen.add(h)
        i += 1
    # never loop-fill — if still short, add remaining unique only once
    if end_marker and end_marker in text:
        text = _insert_before_marker(text, end_marker, to_add)
    else:
        text = text.rstrip() + "\n\n" + "\n\n".join(to_add) + "\n"
    path.write_text(text, encoding="utf-8")


