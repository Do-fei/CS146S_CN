#!/usr/bin/env python3
"""Large single-pass expansion for chapters 04-08 (~3k chars each x 4 blocks)."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "docs" / "novel"

def append(fn, block):
    p = ROOT / fn
    t = p.read_text(encoding="utf-8").rstrip() + "\n\n" + block.strip() + "\n"
    p.write_text(t, encoding="utf-8")
    return len(t)

# Block A - sensory Beijing night
A = """
南横街的风里有煤烟、豆浆、和谁家汤没关火的咸。你走过早点摊收了一半的铁棚，铁勺碰锅，叮一声，像第三排靠窗下课铃慢半拍。你停半秒，不是等，是确认自己还在走。走，别停。停久了，雨会把路名洗掉。洗掉，人就会走到没有站名的地方。没有站名，就不算失踪，算从未被登记。登记是岸上的癖好。你不登记。你找。

你口袋三颗糖，分开装。妈妈那颗在胸前，另外两颗在外套。阿青后来会说，别把岸上的甜和夜里的甜走混。你现在还不认识阿青。你只知道甜的东西要沉。沉住了，比较不容易飘进河里。赵宜教过。教在豆浆里，教在橘子糖里。你当时以为她在说豆浆。"""

# Block B - classroom flashback
B = """
你想起第三排靠窗。她习惯把窗开一条缝，说通风。你说过这样会进雨。她说：进雨才有理由借你伞。你说你伞小。她说：小才好，挤一点。挤一点，就不会走散。你当时以为她说雨。后来想，她也许说别的事。别的事，留到夜里。夜里，你会懂一点。懂一点，就够你继续走。

值日那天，你擦黑板，她洗抹布。水凉，她蹭你袖口，说同桌互助。你笑。笑完继续擦。擦到一半，她在下面排值日歌，跑调，跑调也认真。黑板、抹布、跑调、踩脚。日子像会一直这样。发送失败把日子切了一刀。切了，白天还照常：铃响，点名，空位。"""

# Block C - suspense clues
C = """
23:17。你把时间写在便利贴背面。你写：她在这分钟发信。我在这分钟睡？还是醒？你不确定。不确定就留着。留着，夜里还有事要做。你查流量记录。23:17前后跳了一下，很小。像有人试图连你，连一半，断。断，像发送失败。失败，你就只能走。走去她短信写的地方。

谁删的好友？你查设置，没有删除记录。像系统自己划掉。划掉，人就只能去夜里找。夜里找，别走大路。大路写寻人，写结案。你不写。你等。等十一点。等发送成功。等第三排靠窗不再空。也在，就够你走到赵宜家，走到胡同，走到天桥。"""

# Block D - route foreshadow
D = """
笔记撕页上：阿青管声音，小海管水，老周管路。四个名字里，你还不认识三个。你认识同桌。同桌是位置。位置空着，名字就悬在短信里，发送失败。警察说：这些名字白天问不到。他压低声音：十一点以后，别答应水里的人，别答应倒影，别把一整盘磁带听完。说多了没用。你按她短信走。我们在大路上等。大路等，小的路找。你选小的。

钟停在二十二点五十九。跳到六十，人就被交还给点名册。你还没到店。店在后面一章。你还没上天桥。天桥在第八章。你还没按停止键。停止键在更后面。你现在，只负责把路走实。走实，像还某种同桌的约。约是：十一点后来。别走大路。你收到了。你来了。"""

BLOCKS = [A, B, C, D]

def main():
    for fn in ["04-胡同.md", "05-第三夜.md", "06-胡同深.md", "07-便利店.md", "08-天桥.md"]:
        n = 0
        for i, b in enumerate(BLOCKS):
            tag = f"<!--BIG{i}-->"
            t = ROOT.joinpath(fn).read_text(encoding="utf-8")
            if tag in t:
                continue
            n = append(fn, tag + "\n" + b)
        print(f"{fn}\t{n}")

if __name__ == "__main__":
    main()
